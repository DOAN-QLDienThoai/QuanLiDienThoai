    private void DangnhapActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DangnhapActionPerformed
        TaiKhoanDAO dao = new TaiKhoanDAO();
        String user = txtUser.getText();
        String pass = new String(txtPassword.getPassword());
        TaiKhoanDTO tk = dao.ktraDangNhap(user, pass);
        if (tk != null) {
            dao.capNhatTrangThaiDangNhap(tk.getMaNV(), true);
            String tenNV=nvBus.getTenNVByID(tk.getMaNV());
            Main main = new Main(tenNV);
            main.setMaNhanVien(String.valueOf(tk.getMaNV()));
            main.setTenNhanVien(tenNV);
            jLabel5.setText("Login Success");
            main.setVisible(true);
            this.dispose();
        } else{
        if(user.equals("") && pass.equals("")){
            jLabel5.setText("Enter full information please");
        }
        else {
            jLabel5.setText("Wrong account or password");
        }
        Timer timer = new Timer((5000), new ActionListener() {
            @Override
            public void actionPerformed(ActionEvent e) {
                    jLabel5.setText("");
            }
        });
        timer.setRepeats(false);
        timer.start();
    }//GEN-LAST:event_DangnhapActionPerformed
}
